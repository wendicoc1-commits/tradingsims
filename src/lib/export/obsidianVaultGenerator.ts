/**
 * Menghasilkan konten file Markdown berformat Obsidian untuk setiap simpul
 */
export function generateObsidianMarkdownForNode(node: KnowledgeGraphNode): string {
  const outgoing = TRADESIMS_KNOWLEDGE_EDGES.filter((e) => e.source === node.id);
  const incoming = TRADESIMS_KNOWLEDGE_EDGES.filter((e) => e.target === node.id);

  const outgoingLinks = outgoing
    .map((e) => `- [[${e.target}]] — *${e.relation}* (${e.label || 'Koneksi Langsung'}) [${e.confidence}]`)
    .join('\n');

  const incomingLinks = incoming
    .map((e) => `- [[${e.source}]] — *${e.relation}* (${e.label || 'Dipanggil Oleh'}) [${e.confidence}]`)
    .join('\n');

  return `---
id: "${node.id}"
label: "${node.label}"
category: "${node.category}"
cluster: "${node.cluster}"
filePath: "${node.filePath}"
tags:
  - architecture
  - tradesims
  - ${node.category.toLowerCase()}
---

# ${node.label}

> **Kategori:** \`${node.category}\` | **Klaster:** \`${node.cluster}\`  
> **Lokasi File:** \`${node.filePath}\`

## Deskripsi Arsitektur
${node.description}

## Ketergantungan Keluar (Outgoing Links)
${outgoingLinks || '_Tidak ada ketergantungan keluar._'}

## Dipanggil Oleh (Incoming Links)
${incomingLinks || '_Tidak dipanggil oleh komponen lain secara langsung._'}

---
*Generated by TradeSims Graphify Core & Obsidian Bridge.*
`.trim();
}

/**
 * Menghasilkan map seluruh file Obsidian Vault untuk ekspor lokal
 */
export function generateFullObsidianVault(): Record<string, string> {
  const vault: Record<string, string> = {};

  // 1. CSS Snippet KayVeeG
  vault['.obsidian/snippets/graphview-image.css'] = OBSIDIAN_GRAPHVIEW_IMAGE_CSS;

  // 2. Index Note
  vault['TradeSims-Architecture-Index.md'] = `---
title: "TradeSims Pro Architecture Map"
tags:
  - index
  - architecture
---

# TradeSims Pro Knowledge Graph Index

Selamat datang di Obsidian Vault arsitektur sistem TradeSims Pro. 
Buka **Graph View** (Ctrl/Cmd + G) di Obsidian untuk melihat graf interaktif dengan skinning **KayVeeG Holographic HUD Grid**!

## Komponen Utama
${TRADESIMS_KNOWLEDGE_NODES.map((n) => `- [[${n.id}|${n.label}]] (${n.category})`).join('\n')}
`.trim();

  // 3. Tiap node menjadi satu file markdown
  TRADESIMS_KNOWLEDGE_NODES.forEach((n) => {
    vault[`${n.id}.md`] = generateObsidianMarkdownForNode(n);
  });

  return vault;
}
